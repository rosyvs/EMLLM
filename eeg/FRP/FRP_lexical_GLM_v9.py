            fixations['MW=1'] = (fixations['MW']==1).astype(int)
            # interaction terms
            fixations['WORD_MW=0'] = fixations['MW=0'] * fixations['WORD'] # MW=0 and WORD
            fixations['WORD_MW=1'] = fixations['MW=1'] * fixations['WORD'] # MW=1 and WORD
            fixations['STOP_MW=0'] = fixations['MW=0'] * fixations['STOP'] # MW=0 and STOP
            fixations['STOP_MW=1'] = fixations['MW=1'] * fixations['STOP'] # MW=1 and STOP
            fixations['PUNC_MW=0'] = fixations['MW=0'] * fixations['PUNC'] # MW=0 and PUNC
            fixations['PUNC_MW=1'] = fixations['MW=1'] * fixations['PUNC'] # MW=1 and PUNC

            ##### covariates

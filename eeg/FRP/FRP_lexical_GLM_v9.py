            events = events[events['task'].str.contains('reading|sham')]
            fixations = events[events['event_type'].str.contains('Fixation') ]
            blinks = events[events['event_type'].str.contains('Blink')]
            task_events = events[events['event_type'].str.contains('ButtonPress')]       

            # get sacc amp outliers for this participant as +- 3 STDEV from the mean INBOUND_SAC_AMPLITUDE
            sacc_amp_outliers = np.abs(fixations['INBOUND_SAC_AMPLITUDE'] - fixations['INBOUND_SAC_AMPLITUDE'].mean()) > 3*fixations['INBOUND_SAC_AMPLITUDE'].std()
            # drop fixations with extreme duration or saccade amplitude
            fixations = fixations[~sacc_amp_outliers]
            # remove fixations with duration <50 or >1000
            fixations = fixations[(fixations['duration_sec'] > 0.05) & (fixations['duration_sec'] < 1)]
            fixations = fixations.set_index('eeg_sample')
            
            # ##### word fixaitons as a separate event
            # fixations['event_type'].loc[fixations['IA_ID']!=-1 & (fixations['task']=='reading')] = 'FixationWord' 
            # fixations['event_type'].loc[fixations['IA_ID']!=-1 & (fixations['task']=='reading') & (fixations['stop_word']==1)] = 'STOP' # for stop words
            # fixations['event_type'].loc[fixations['IA_ID']!=-1 & (fixations['task']=='reading') & (fixations['punctuation']==1)] = 'PUNC' # for punctuation

            # ##### type of fixation as biary dummy coded variable (intercept = all fixations)
            fixations['WORD'] = np.where((fixations['IA_ID']!=-1) & (fixations['task']=='reading') & (fixations['stop_word']==0), 1, 0) # for words
            fixations['STOP'] = np.where((fixations['task']=='reading') & (fixations['stop_word']==1), 1, 0) # for stop words
